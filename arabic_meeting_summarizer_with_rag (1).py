    try:
        arabic_analysis = arabic_model_understand(full_text)
        print(f"   ✅ Mistral Saba أنتج {len(arabic_analysis)} حرف من التحليل")
    except Exception as e:
        print(f"   ⚠️  Mistral Saba فشل: {e}")
        arabic_analysis = ""

    print("🧠 Gemini: جاري بناء التقرير الهيكلي ...")
    final_report = gemini_report(arabic_analysis, full_text)
    print(f"   ✅ Gemini أنتج {len(final_report)} حرف")
    return final_report


