def show_ram():
    ram = psutil.virtual_memory()
    filled = int(ram.percent / 5)
    bar = '█' * filled + '░' * (20 - filled)
    print(f'RAM  [{bar}] {ram.used/1e9:.1f}/{ram.total/1e9:.1f} GB  ({ram.percent:.0f}%)')
    if torch.cuda.is_available():
        alloc = torch.cuda.memory_allocated() / 1e9
        total = torch.cuda.get_device_properties(0).total_memory / 1e9
        print(f'GPU  {alloc:.1f}/{total:.1f} GB  |  CUDA {torch.version.cuda}')
    else:
        print('GPU  not available — CPU mode (slower, but works)')

def free_memory(*model_vars):
    """Delete model variables and flush GPU cache."""
    for v in model_vars:
        try:
            del v
        except Exception:
            pass
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    print('🧹 Memory freed')

