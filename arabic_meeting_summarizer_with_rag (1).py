def arabic_model_understand(full_text: str, max_chars: int = 10000) -> str:
    """Mistral Saba يقرأ النص العربي كاملاً ويستخرج المعلومات الجوهرية."""
    truncated = full_text[:max_chars]
    messages = [
        {
            "role": "system",
            "content": (
                "أنت مساعد متخصص في تحليل اجتماعات العمل باللغة العربية الفصيحة. "
                "مهمتك استخراج المعلومات الجوهرية من نص الاجتماع بدقة عالية."
            ),
        },
        {
            "role": "user",
            "content": (
                f"حلّل نص الاجتماع التالي واستخرج:\n"
                f"1. المواضيع الرئيسية التي نوقشت\n"
                f"2. القرارات المتخذة مع ذكر المسؤول عن كل قرار\n"
                f"3. المهام الموكلة لكل شخص والمواعيد النهائية\n"
                f"4. النقاط الخلافية أو غير المحسومة\n"
                f"5. أسماء المشاركين والأدوار إن وُجدت\n\n"
                f"نص الاجتماع:\n{truncated}"
            ),
        },
    ]
    response = arabic_client.chat.completions.create(
        model=ARABIC_MODEL_ID,
        messages=messages,
        max_tokens=1200,
        temperature=0.3,
    )
    return response.choices[0].message.content.strip()


def gemini_report(arabic_analysis: str, full_text: str, max_chars: int = 12000) -> str:
    """Gemini يبني التقرير الهيكلي بناءً على تحليل النموذج العربي."""
    arabic_section = (
        f"**تحليل Mistral Saba العربي للاجتماع:**\n{arabic_analysis}\n\n"
        if arabic_analysis else ""
    )
    prompt = f"""أنت محلل اجتماعات محترف متخصص باللغة العربية.

{arabic_section}**النص الكامل للاجتماع:**
{full_text[:max_chars]}

أنشئ تقريراً شاملاً واحترافياً بالتنسيق التالي بالضبط:

## 1. جدول القرارات الرئيسية
| # | القرار | التفاصيل | المسؤول | الموعد |
|---|--------|----------|---------|--------|

## 2. جدول المهام والمسؤوليات
| # | المهمة | المسؤول | الموعد | الأولوية |
|---|--------|---------|--------|----------|

## 3. أبرز النقاط المطروحة
- نقطة 1
- نقطة 2
- نقطة 3

## 4. خريطة ذهنية
- **الموضوع الرئيسي**: ...
  - **فرع 1**: ...
  - **فرع 2**: ...
  - **فرع 3**: ...

## 5. الخلاصة التنفيذية
(5-7 أسطر موجزة تصف محور الاجتماع ونتائجه)

ابدأ مباشرة بالعنوان الأول دون أي مقدمة.
"""
    for attempt in range(5):
        try:
            response = gemini_client.models.generate_content(
                model="gemini-2.5-flash",
                contents=prompt,
            )
            return response.text.strip()
        except Exception as e:
            if "503" in str(e) or "UNAVAILABLE" in str(e):
                wait = 20 * (attempt + 1)
                print(f"   ⏳ Gemini مشغول، انتظر {wait}ث ({attempt+1}/5)...")
                time.sleep(wait)
            else:
                raise e
    raise RuntimeError("❌ Gemini غير متاح بعد 5 محاولات")


def hybrid_summary(full_text: str) -> str:
    """Mistral Saba يفهم → Gemini يبني التقرير."""
