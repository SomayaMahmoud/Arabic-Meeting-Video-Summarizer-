def llm_judge_evaluate(transcript: str, summary: str, reference: str = "", max_chars: int = 12000) -> dict:
    """يستخدم Gemini كـ'حكم' لتقييم جودة الملخص بطريقة شبيهة بالتقييم البشري."""

    reference_block = (
        f"\n**ملخص مرجعي (للمقارنة فقط):**\n{reference}\n"
        if reference else ""
    )

    judge_prompt = f"""أنت مقيّم خبير ومحايد لملخصات اجتماعات الأعمال باللغة العربية.

**النص الكامل للاجتماع (الحقيقة المرجعية):**
{transcript[:max_chars]}
{reference_block}
**الملخص المطلوب تقييمه:**
{summary}

قيّم الملخص أعلاه على المعايير التالية، كل معيار من 1 إلى 10:
1. faithfulness (الدقة والأمانة): هل المعلومات صحيحة وغير مُختلقة (لا Hallucination)؟
2. coverage (الشمولية): هل يغطي أهم القرارات والمهام والنقاط؟
3. coherence (التماسك والوضوح): هل التنظيم والصياغة مفهومة ومنطقية؟
4. conciseness (الإيجاز): هل الملخص موجز دون حشو أو تكرار؟
5. language_quality (جودة اللغة العربية): هل اللغة سليمة نحويًا وأسلوبيًا؟

أعد إجابتك بصيغة JSON فقط، بدون أي شرح أو نص خارج JSON، وبالشكل التالي بالضبط:
{{
  "faithfulness":     {{"score": 0, "justification": "..."}},
  "coverage":         {{"score": 0, "justification": "..."}},
  "coherence":        {{"score": 0, "justification": "..."}},
  "conciseness":      {{"score": 0, "justification": "..."}},
  "language_quality": {{"score": 0, "justification": "..."}},
  "overall_score": 0,
  "overall_comment": "..."
}}"""

    for attempt in range(5):
        try:
            response = gemini_client.models.generate_content(
                model="gemini-2.5-flash",
                contents=judge_prompt,
            )
            raw = response.text.strip()
            raw = re.sub(r"^```json\s*|\s*```$", "", raw, flags=re.MULTILINE).strip()
            return json.loads(raw)
        except json.JSONDecodeError as e:
            print(f"   ⚠️  فشل تحليل JSON من Gemini، إعادة المحاولة... ({e})")
        except Exception as e:
            if "503" in str(e) or "UNAVAILABLE" in str(e):
                wait = 20 * (attempt + 1)
                print(f"   ⏳ Gemini مشغول، انتظر {wait}ث ({attempt+1}/5)...")
                time.sleep(wait)
            else:
                raise e
    raise RuntimeError("❌ فشل تقييم LLM Judge بعد عدة محاولات")


