# ── Simple speaker diarization ─────────────────────────
# Uses pause-length heuristic: long pause → speaker change
def simple_diarize(segs, pause_threshold: float = 1.5, max_speakers: int = 6):
    """Assign speaker labels based on inter-segment pauses."""
    speaker_id = 0
    prev_end    = 0.0
    labelled    = []
    for seg in segs:
        if seg.start - prev_end > pause_threshold:
            speaker_id = (speaker_id + 1) % max_speakers
        labelled.append({
            "speaker": f"Speaker_{speaker_id + 1}",
            "start":   round(seg.start, 2),
            "end":     round(seg.end,   2),
            "text":    seg.text.strip(),
        })
        prev_end = seg.end
    return labelled

# Override max speakers if user provided a hint
