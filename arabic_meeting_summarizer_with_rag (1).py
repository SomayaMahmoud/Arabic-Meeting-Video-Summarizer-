import re
from rouge_score import rouge_scorer

# ── Tokenizer مخصص للعربية ──────────────────────────────
# المُجزّئ (tokenizer) الافتراضي في rouge_score يحذف كل الحروف غير اللاتينية
# (regex: [^a-z0-9]+) لذا نحتاج مُجزّئًا يدعم اليونيكود/العربية.
class ArabicTokenizer:
    _tashkeel = re.compile(r'[\u064B-\u0652\u0670\u0640]')  # تشكيل + تطويل

    def tokenize(self, text: str):
        text = self._tashkeel.sub('', text)
        return re.findall(r'\w+', text, flags=re.UNICODE)

